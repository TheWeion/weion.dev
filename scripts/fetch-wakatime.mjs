#!/usr/bin/env node
/**
 * Build-time WakaTime fetcher.
 *
 * Reads WAKATIME_API_KEY from the environment and writes
 * `src/data/wakatime.generated.ts` with telemetry data derived from the
 * `/users/current/stats/last_7_days` and `/users/current/summaries` endpoints.
 *
 * If the key is absent or the fetch fails, the existing `wakatime.generated.ts`
 * (if any) is preserved as the fallback — we'd rather serve last-known-good
 * numbers than fakes. Only when no prior file exists is a minimal empty
 * bootstrap written, so the build still succeeds. This runs from `predev`
 * and `prebuild` so the generated file is always present before tsc/Vite
 * read it.
 *
 * Netlify: set WAKATIME_API_KEY in the site's environment variables.
 * A scheduled build (once daily) is enough to keep the numbers fresh.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const OUT_PATH = resolve(__dirname, '../src/data/wakatime.generated.ts');
const ENV_PATH = resolve(__dirname, '../.env');

/**
 * Tiny .env loader. Real env vars (e.g. from Netlify) always win; we only fill
 * in what's missing. Absent .env is fine. Supports KEY=value, # comments, and
 * single/double-quoted values.
 */
async function loadDotEnv(path) {
  let raw;
  try {
    raw = await readFile(path, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') return;
    throw err;
  }
  for (const line of raw.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    // Overwrite if unset OR empty — an exported-but-empty shell var would
    // otherwise shadow the .env value.
    if (key && !process.env[key]) process.env[key] = value;
  }
}

await loadDotEnv(ENV_PATH);

/** Colors cycled through, in order, for the top languages. "Other" is always muted. */
const BAR_COLOR_TOKENS = ['cyan', 'amber', 'magenta', 'halo', 'ok'];

/**
 * Bootstrap file written only when a fetch is not possible AND no previous
 * `wakatime.generated.ts` exists to preserve. Renders empty panels rather
 * than fake data — the build still succeeds and the next scheduled deploy
 * (or a local run with a valid key) will populate real numbers.
 */
const BOOTSTRAP_FILE = `/**
 * AUTO-GENERATED by scripts/fetch-wakatime.mjs — bootstrap (no data yet).
 * Generated: ${new Date().toISOString()}
 *
 * Written because the WakaTime fetch was not possible and no prior
 * generated file existed to preserve. Re-run once WAKATIME_API_KEY is set
 * and the API is reachable.
 */
import type { TelemetryBar, TelemetryHeatmapDay } from '@/types';

export const telemetryBars: TelemetryBar[] = [];
export const telemetryTiles = [] as const;
export const telemetryHeatmap: TelemetryHeatmapDay[] = [];
export const telemetryYearTiles = [] as const;
`;

function fmtHM(totalSeconds) {
  const secs = Math.max(0, Math.round(totalSeconds || 0));
  const h = Math.floor(secs / 3600);
  const m = Math.floor((secs % 3600) / 60);
  return `${h}h ${String(m).padStart(2, '0')}m`;
}

async function wakaFetch(apiKey, path) {
  const url = new URL(`https://wakatime.com/api/v1${path}`);
  url.searchParams.set('api_key', apiKey);
  const res = await fetch(url);
  if (!res.ok) {
    const body = await res.text().catch(() => '');
    throw new Error(`WakaTime ${path} -> ${res.status} ${res.statusText} ${body.slice(0, 200)}`);
  }
  return res.json();
}

function buildBars(languages) {
  const nonZero = (languages || []).filter((l) => (l.total_seconds ?? 0) > 0);
  const top = nonZero.slice(0, 5);
  const rest = nonZero.slice(5);

  const bars = top.map((l, i) => ({
    label: l.name,
    pct: Math.round((l.percent ?? 0) * 10) / 10,
    colorToken: BAR_COLOR_TOKENS[i],
  }));

  const otherPct = rest.reduce((acc, l) => acc + (l.percent ?? 0), 0);
  if (otherPct >= 0.1) {
    bars.push({
      label: 'Other',
      pct: Math.round(otherPct * 10) / 10,
      colorToken: 'muted',
    });
  }

  return bars;
}

function buildYearHeatmap(summaries) {
  const days = (summaries?.data ?? [])
    .map((d) => ({
      date: d?.range?.date ?? '',
      seconds: d?.grand_total?.total_seconds ?? 0,
    }))
    .filter((p) => p.date);

  // Quartile thresholds across non-zero days so buckets adapt to this user's
  // activity range (ignoring zero-days keeps low-activity-but-daily weeks readable).
  const nonZero = days
    .map((p) => p.seconds)
    .filter((s) => s > 0)
    .sort((a, b) => a - b);
  const q = (pct) =>
    nonZero.length ? nonZero[Math.min(nonZero.length - 1, Math.floor(nonZero.length * pct))] : 0;
  const t1 = q(0.25);
  const t2 = q(0.5);
  const t3 = q(0.75);

  return days.map(({ date, seconds }) => {
    let level = 0;
    if (seconds <= 0) level = 0;
    else if (seconds <= t1) level = 1;
    else if (seconds <= t2) level = 2;
    else if (seconds <= t3) level = 3;
    else level = 4;
    return { date, level };
  });
}

function formatBestDay(iso) {
  if (!iso) return '—';
  const d = new Date(`${iso}T00:00:00Z`);
  if (Number.isNaN(d.getTime())) return '—';
  const month = d.toLocaleString('en-US', { month: 'short', timeZone: 'UTC' }).toUpperCase();
  return `${month} ${String(d.getUTCDate()).padStart(2, '0')}`;
}

function buildYearTiles(yearStats, yearSummaries) {
  let totalSecs = 0;
  let bestDate = '';
  let bestSecs = 0;
  for (const d of yearSummaries?.data ?? []) {
    const secs = d?.grand_total?.total_seconds ?? 0;
    totalSecs += secs;
    if (secs > bestSecs) {
      bestSecs = secs;
      bestDate = d?.range?.date ?? '';
    }
  }
  const topLang = yearStats?.data?.languages?.[0]?.name ?? '—';
  return [
    { label: 'TOTAL', value: fmtHM(totalSecs), colorToken: 'cyan' },
    { label: 'TOP LANG', value: topLang, colorToken: 'amber' },
    { label: 'BEST DAY', value: formatBestDay(bestDate), colorToken: 'ok' },
  ];
}

function computeStreak(summaries) {
  // summaries.data is oldest -> newest; walk newest -> oldest.
  const days = [...(summaries?.data ?? [])].reverse();
  let streak = 0;
  let started = false;
  for (const day of days) {
    const secs = day?.grand_total?.total_seconds ?? 0;
    if (secs > 0) {
      streak++;
      started = true;
    } else if (started) {
      // Gap after at least one coded day ends the streak.
      break;
    }
    // Leading zero-days (today might not have logged time yet) don't break the streak.
    // We only break once we've seen at least one coded day followed by a zero day.
  }
  return streak;
}

/**
 * WakaTime personal API keys are `waka_` + a UUIDv4 (36 chars) = 41 chars.
 * If the loaded value doesn't match, bail early with a shape-only diagnostic
 * (no prefix/suffix leaked to the log) — this is the usual symptom of a
 * stray character or copy-paste glitch in .env.
 */
const WAKA_KEY_RE = /^waka_[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Attempt a full, fresh fetch. Returns either a complete dataset or a
 * failure reason — partial results are treated as failures so the existing
 * generated file can be preserved as-is (no mixing fresh + stale values).
 */
async function collect() {
  const apiKey = process.env.WAKATIME_API_KEY;
  if (!apiKey) {
    return { ok: false, reason: 'WAKATIME_API_KEY not set' };
  }
  if (!WAKA_KEY_RE.test(apiKey)) {
    return {
      ok: false,
      reason: `WAKATIME_API_KEY looks malformed (length=${apiKey.length}, expected 41 matching /waka_<uuid>/). Check .env for stray characters.`,
    };
  }

  try {
    // Summaries requires explicit start/end — `range=last_year` is not accepted.
    const today = new Date();
    today.setUTCHours(0, 0, 0, 0);
    const yearAgo = new Date(today);
    yearAgo.setUTCDate(yearAgo.getUTCDate() - 364);
    const yearStart = yearAgo.toISOString().slice(0, 10);
    const yearEnd = today.toISOString().slice(0, 10);

    const [stats, summaries, yearStats, yearSummaries] = await Promise.all([
      wakaFetch(apiKey, '/users/current/stats/last_7_days'),
      wakaFetch(apiKey, '/users/current/summaries?range=last_30_days'),
      wakaFetch(apiKey, '/users/current/stats/last_year'),
      wakaFetch(apiKey, `/users/current/summaries?start=${yearStart}&end=${yearEnd}`),
    ]);

    const bars = buildBars(stats?.data?.languages);
    if (bars.length === 0) {
      return { ok: false, reason: 'WakaTime returned no language data' };
    }

    const heatmap = buildYearHeatmap(yearSummaries);
    if (heatmap.length === 0) {
      return { ok: false, reason: 'WakaTime returned no year summaries' };
    }

    const avgSecs = stats?.data?.daily_average ?? 0;
    const peakSecs = stats?.data?.best_day?.total_seconds ?? 0;
    const streak = computeStreak(summaries);

    const tiles = [
      { label: 'AVG/DAY', value: fmtHM(avgSecs), colorToken: 'amber' },
      { label: 'PEAK', value: fmtHM(peakSecs), colorToken: 'cyan' },
      { label: 'STREAK', value: `${streak} day${streak === 1 ? '' : 's'}`, colorToken: 'ok' },
    ];

    const yearTiles = buildYearTiles(yearStats, yearSummaries);

    return {
      ok: true,
      bars,
      tiles,
      heatmap,
      yearTiles,
      source: 'wakatime',
      streak,
    };
  } catch (err) {
    return { ok: false, reason: `fetch failed — ${err.message}` };
  }
}

async function fileExists(path) {
  try {
    await readFile(path, 'utf8');
    return true;
  } catch (err) {
    if (err.code === 'ENOENT') return false;
    throw err;
  }
}

function serializeBar(b) {
  return `  { label: ${JSON.stringify(b.label)}, pct: ${b.pct}, color: colors.${b.colorToken} },`;
}

function serializeTile(t) {
  return `  { label: ${JSON.stringify(t.label)}, value: ${JSON.stringify(t.value)}, color: colors.${t.colorToken} },`;
}

function serializeHeatmapDay(d) {
  return `  { date: ${JSON.stringify(d.date)}, level: ${d.level} },`;
}

function renderFile({ bars, tiles, heatmap, yearTiles, source }) {
  const header = `/**
 * AUTO-GENERATED by scripts/fetch-wakatime.mjs — do not edit by hand.
 * Source:    ${source}
 * Generated: ${new Date().toISOString()}
 */`;

  return `${header}
import { colors } from '@/lib/tokens';
import type { TelemetryBar, TelemetryHeatmapDay } from '@/types';

export const telemetryBars: TelemetryBar[] = [
${bars.map(serializeBar).join('\n')}
];

export const telemetryTiles = [
${tiles.map(serializeTile).join('\n')}
] as const;

export const telemetryHeatmap: TelemetryHeatmapDay[] = [
${heatmap.map(serializeHeatmapDay).join('\n')}
];

export const telemetryYearTiles = [
${yearTiles.map(serializeTile).join('\n')}
] as const;
`;
}

const result = await collect();
await mkdir(dirname(OUT_PATH), { recursive: true });

if (result.ok) {
  await writeFile(OUT_PATH, renderFile(result), 'utf8');
  console.log(
    `[wakatime] OK — ${result.bars.length} bars, streak=${result.streak}, heatmap=${result.heatmap.length} days`,
  );
  console.log(`[wakatime] wrote ${OUT_PATH}`);
} else if (await fileExists(OUT_PATH)) {
  // Preserve the last-known-good file instead of clobbering it with fakes.
  // A stale header is the only downside; the data stays real.
  console.warn(`[wakatime] ${result.reason} — keeping existing ${OUT_PATH}.`);
} else {
  console.warn(`[wakatime] ${result.reason} — no existing data, writing empty bootstrap.`);
  await writeFile(OUT_PATH, BOOTSTRAP_FILE, 'utf8');
}
